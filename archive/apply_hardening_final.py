def _norm(b: bytes) -> bytes:
    if b.startswith(b"\xef\xbb\xbf"):
        b = b[3:]
    return b.replace(b"\r\n", b"\n")


def _sha(b: bytes) -> str:
    return hashlib.sha256(_norm(b)).hexdigest()


def _ops() -> list[dict]:
    return json.loads(zlib.decompress(base64.b64decode("".join(PAYLOAD.split()))).decode("utf-8"))


def _encode(content: str, *, crlf: bool, bom: bool) -> bytes:
    text = content.replace("\r\n", "\n")
    if crlf:
        text = text.replace("\n", "\r\n")
    data = text.encode("utf-8")
    return (b"\xef\xbb\xbf" + data) if bom else data


def plan(root: Path) -> tuple[list[tuple[dict, str]], list[str]]:
    actions, conflicts = [], []
    for op in _ops():
        path = root / op["path"]
        exists = path.exists()
        raw = path.read_bytes() if exists else b""
        current = _sha(raw) if exists else None
        # A .py file is only "done" without a BOM: some operations exist
        # solely to strip one, and the hash deliberately ignores BOMs.
        bom_pending = op["path"].endswith(".py") and raw.startswith(b"\xef\xbb\xbf")
        if op["op"] == "modify":
            if not exists:
                conflicts.append(f"MISSING   {op['path']}")
            elif current == op["target_sha"] and not bom_pending:
                actions.append((op, "already"))
            elif current in (op["base_sha"], op["target_sha"]):
                actions.append((op, "write"))
            else:
                conflicts.append(f"CONFLICT  {op['path']} (local changes; not tier-3, not final)")
        elif op["op"] == "add":
            if not exists:
                actions.append((op, "write"))
            elif current == op["target_sha"]:
                actions.append((op, "already"))
            else:
                conflicts.append(f"CONFLICT  {op['path']} (exists with different content)")
        elif op["op"] == "delete":
            if not exists:
                actions.append((op, "already"))
            elif current == op["base_sha"]:
                actions.append((op, "delete"))
            else:
                conflicts.append(f"CONFLICT  {op['path']} (to delete, but locally modified)")
    return actions, conflicts


def apply(root: Path) -> int:
    actions, conflicts = plan(root)
    if conflicts:
        print("Refusing to write anything:\n  " + "\n  ".join(conflicts))
        return 2
    todo = [(op, a) for op, a in actions if a != "already"]
    if not todo:
        print(f"No changes: all {len(actions)} operations already applied.")
        return 0
    stamp = _dt.datetime.now().strftime("%Y%m%d-%H%M%S")
    backup = root / BACKUP_DIR / stamp
    manifest = {"created": [], "backed_up": []}
    backup.mkdir(parents=True, exist_ok=True)
    for op, _ in todo:
        src = root / op["path"]
        if src.exists():
            dst = backup / op["path"]
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)
            manifest["backed_up"].append(op["path"])
        else:
            manifest["created"].append(op["path"])
    (backup / "MANIFEST.json").write_text(json.dumps(manifest, indent=1), encoding="utf-8")
    done: list[str] = []
    try:
        for op, action in todo:
            path = root / op["path"]
            if action == "delete":
                path.unlink()
            else:
                if path.exists():
                    raw = path.read_bytes()
                    crlf = b"\r\n" in raw
                    bom = raw.startswith(b"\xef\xbb\xbf") and not op["path"].endswith(".py")
                else:
                    crlf, bom = os.name == "nt", False
                path.parent.mkdir(parents=True, exist_ok=True)
                tmp = path.with_name(path.name + ".hardening-tmp")
                tmp.write_bytes(_encode(op["content"], crlf=crlf, bom=bom))
                os.replace(tmp, path)
            done.append(op["path"])
    except Exception as exc:  # noqa: BLE001
        print(f"Write failed at {op['path']}: {exc}. Restoring backup ...")
        _restore(root, backup)
        return 3
    counts = {}
    for _, a in todo:
        counts[a] = counts.get(a, 0) + 1
    print(f"Applied {len(todo)} operations ({counts}); {len(actions) - len(todo)} were already in place.")
    print(f"Backup: {backup}")
    return 0


def _restore(root: Path, backup: Path) -> None:
    manifest = json.loads((backup / "MANIFEST.json").read_text(encoding="utf-8"))
    for rel in manifest["backed_up"]:
        target = root / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(backup / rel, target)
    for rel in manifest["created"]:
        target = root / rel
        if target.exists():
            target.unlink()


def rollback(root: Path) -> int:
    base = root / BACKUP_DIR
    stamps = sorted(p for p in base.iterdir() if p.is_dir()) if base.exists() else []
    if not stamps:
        print("No backup to restore.")
        return 1
    _restore(root, stamps[-1])
    print(f"Restored {stamps[-1]}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="FlowPilot hardening final apply engine")
    parser.add_argument("--root", default=".", help="repository root (holds backend/ and frontend/)")
    parser.add_argument("--check", action="store_true", help="verify only; write nothing")
    parser.add_argument("--rollback", action="store_true", help="restore the latest backup")
    args = parser.parse_args()
    root = Path(args.root).resolve()
    if not (root / "backend").is_dir() or not (root / "frontend").is_dir():
        print(f"{root} does not look like the FlowPilot repository root (needs backend/ and frontend/).")
        return 1
    if args.rollback:
        return rollback(root)
    if args.check:
        actions, conflicts = plan(root)
        pending = sum(1 for _, a in actions if a != "already")
        print(f"{len(actions)} operations ok ({pending} to apply, {len(actions) - pending} already applied); {len(conflicts)} conflicts.")
        for c in conflicts:
            print("  " + c)
        return 0 if not conflicts else 2
    return apply(root)


if __name__ == "__main__":
    sys.exit(main())
